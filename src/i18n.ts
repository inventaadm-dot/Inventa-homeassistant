export type StringKey = keyof typeof STRINGS.es;

export function lang(hass?: HomeAssistant): 'es' | 'en' {
  const l = (hass?.locale?.language || hass?.language || navigator.language || 'es').toLowerCase();
  return l.startsWith('es') ? 'es' : 'en';
}

export function t(hass: HomeAssistant | undefined, key: StringKey, vars?: Record<string, string | number>): string {
  let s: string = STRINGS[lang(hass)][key] ?? STRINGS.es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** `hass` del documento, para etiquetas del editor visual (que no recibe hass). */
export function docHass(): HomeAssistant | undefined {
  return (document.querySelector('home-assistant') as any)?.hass;
}

/** `computeLabel` para el editor visual; `aliases` traduce nombres de opción a claves de texto. */
export function labeler(aliases: Record<string, string> = {}) {
  return (s: { name: string }) => t(docHass(), (aliases[s.name] || s.name) as StringKey) || s.name;
}
